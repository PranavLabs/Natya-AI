def collect_user_preference_basic():
    """Basic method to collect user movie/TV show preference"""
    print("\n🎬 Movie/TV Show Recommendation System (TMDb + AI Chat Powered)")
    print("---------------------------------")

    media_type_choice = ""
    while media_type_choice not in ['movie', 'tv']:
        media_type_choice = input("Do you want to search for a [movie] or a [tv] show? ").lower().strip()
        if media_type_choice not in ['movie', 'tv']:
            print("Invalid choice. Please type 'movie' or 'tv'.")

    print(f"Tell me what kind of {media_type_choice} you're in the mood for:")
    print("(Describe your preferences in detail - genre, mood, style, year, language/industry, etc.)") # Updated prompt
    print()

    user_input = input(f"Your {media_type_choice} preference: ")
    return user_input.strip(), media_type_choice

