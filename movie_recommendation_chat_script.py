def get_movie_genre_ids():
    """
    Fetches movie genre IDs and their names from TMDb.
    This function interacts with TMDb to get a list of all available movie genres
    and maps their names (lowercase) to their corresponding IDs.
    """
    try:
        g = tmdb.Genres() # Creates an instance of the TMDb Genres API.
        genres = {x['name'].lower(): x['id'] for x in g.movie_list()['genres']} # Fetches movie genres and creates a dictionary.
        print(f"Successfully fetched {len(genres)} movie genres from TMDb.") # Prints a success message.
        return genres # Returns the dictionary of movie genres.
    except tmdb.exceptions.TMDbException as e: # Catches exceptions specific to TMDb API calls.
        print(f"Error fetching movie genres from TMDb: {e}") # Prints the error message.
        print("Please check your TMDb API key and network connection. Exiting.") # Provides troubleshooting advice.
        exit(1) # Exits the script due to a critical error.
    except requests.exceptions.RequestException as e: # Catches general network-related exceptions.
        print(f"Network error fetching movie genres from TMDb: {e}") # Prints the network error message.
        print("Please check your internet connection. Exiting.") # Provides troubleshooting advice.
        exit(1) # Exits the script due to a critical error.

